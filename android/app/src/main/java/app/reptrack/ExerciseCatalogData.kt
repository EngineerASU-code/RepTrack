internal fun normalizeExerciseCatalogLabel(value: String): String =
    value.trim().lowercase(Locale.ROOT).replace('ё', 'е').replace(Regex("[^a-zа-я0-9]+"), " ").trim()

private val exerciseCatalogNameIndex: Map<String, ExerciseCatalogEntry> = exerciseCatalog
    .flatMap { entry -> (listOf(entry.name) + entry.aliases).map { normalizeExerciseCatalogLabel(it) to entry } }
    .groupBy({ it.first }, { it.second })
    .mapNotNull { (label, entries) -> entries.distinctBy(ExerciseCatalogEntry::id).singleOrNull()?.let { label to it } }
    .toMap()

internal fun exerciseCatalogEntryForName(name: String): ExerciseCatalogEntry? =
    exerciseCatalogNameIndex[normalizeExerciseCatalogLabel(name)]

