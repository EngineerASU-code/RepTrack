    name = name,
    aliases = listOf(alias) + extraAliases,
    primaryMuscles = listOf(primary),
    secondaryMuscles = secondary,
    equipment = equipment,
    setup = setup,
    steps = steps,
    breathing = breathing,
    commonMistakes = mistakes.split("; "),
    safetyNotes = safety,
    artKey = exerciseCatalogArtworkById[id] ?: error("Для упражнения $id не назначена иллюстрация"),
